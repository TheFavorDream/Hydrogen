    void Grid::GenerateGrid() noexcept
    {

        

        //Create a quad
        std::vector<VecF2> Positions = 
        {
            VecF2( -1.0, -1.0f),
            VecF2( -1.0f, 1.0f),
            VecF2(  1.0f, 1.0f),
            VecF2(  1.0f,-1.0f)
        };

        uint16 Indices[] = {
            0, 1, 2,
            2, 3, 0
        };

        m_VertexBuffer = Renderer::Self().InstanceVertexBuffer();
        m_VertexBuffer->CreateBuffer(sizeof(VecF2)*4);
        m_VertexBuffer->UploadData(Positions.data(), sizeof(VecF2)*4);

        m_IndexBuffer = Renderer::Self().InstanceIndexBuffer();
        m_IndexBuffer->CreateBuffer(sizeof(uint16)*6, 6, VK_INDEX_TYPE_UINT16);
        m_IndexBuffer->UploadData(Indices, sizeof(uint16)*6);


        //DescriptorSet Layout:
        DescriptorSetLayoutConfiguration DescLayoutConf;
        DescLayoutConf.AddBinding(DescriptorBinding{
            .Binding = 0,
            .Count   = 1,
            .Stage   = HYD_SHADER_STAGE_VERTEX_BIT,
            .Type    = HYD_DESCRIPTOR_TYPE_UNIFORM_BUFFER
        });

        HYD_ID_SPACE DescLayout = Renderer::Self().CreateDescriptorSetLayout( DescLayoutConf);

        //Pipeline Layout:
        PipelineLayoutConfiguration LayoutConf;
        LayoutConf.AttachDescriptorLayout(DescLayout);
        HYD_ID_SPACE LayoutID = Renderer::Self().CreatePipelineLayout(LayoutConf);


        //Uniform Buffers:
		HYD_ID_SPACE UniformBufferSetID = Renderer::Self().AllocateDescriptorSet(DescLayout);

		m_Uniform = Renderer::Self().CreateUniformBuffer(
			sizeof(GridUniformData),
			ShaderUniformBinding{
                .Binding     = 0,
                .Set         = 0,
                .ShaderStage = HYD_SHADER_STAGE_VERTEX_BIT,
                .Type        = HYD_DESCRIPTOR_TYPE_UNIFORM_BUFFER
            },
			UniformBufferSetID
		);


        //Create Pipeline:
        Hydrogen::Internal::Vulkan::VertexAttribute Attribute;
        Attribute.m_BindingDescriptions.push_back(
            VkVertexInputBindingDescription{
                .binding   = 0,
                .stride    = sizeof(VecF2),
                .inputRate = VK_VERTEX_INPUT_RATE_VERTEX
        });

        Attribute.m_AttributeDescriptions.push_back(
            VkVertexInputAttributeDescription{
                .location = 0, 
                .binding  = 0,
                .format   = VK_FORMAT_R32G32_SFLOAT,
                .offset   = 0
            }
        );


        GraphicsPipelineConfiguration PipelineConf;


        Buffer VertexSource(
            new uint8[VertexShaderSizeInBytes]{GridVertexSpv},
            VertexShaderSizeInBytes
        );

        Buffer FragmentSource(
            new uint8[FragmentShaderSizeInBytes]{GridFragmentSpv},
            FragmentShaderSizeInBytes
        );

        ShaderConfiguration VertexSh{
            .Type      = HYD_STAGE_VERTEX_SHADER,
            .Binary    = std::move(VertexSource),
            .EntryName = "main",
        };
        ShaderConfiguration FragmentSh{
            .Type      = HYD_STAGE_FRAGMENT_SHADER,
            .Binary    = std::move(FragmentSource),
            .EntryName = "main",
        };



        PipelineConf.SetPipelineLayout(LayoutID);
        PipelineConf.AddVertexBufferLayout(Attribute);
        PipelineConf.AttachShader(VertexSh);
        PipelineConf.AttachShader(FragmentSh);
        PipelineConf.SetPrimitiveTogology();
        PipelineConf.SetRasterizer(HYD_POLYGON_MODE_FILL, HYD_CULL_MODE_NONE, HYD_FRONT_FACE_CLOCKWISE);
        PipelineConf.SetDepthStencil(false, false);
        PipelineConf.SetSubpass(0);
        

        //Color Blending:

        ColorBlendState BlendState1;
        BlendState1.colorWriteMask      = HYD_COLOR_COMPONENT_R | HYD_COLOR_COMPONENT_G | HYD_COLOR_COMPONENT_B | HYD_COLOR_COMPONENT_A;
        BlendState1.blendEnable         = VK_TRUE;
        BlendState1.colorBlendOp        = VkBlendOp(HYD_BLEND_OP_ADD);
        BlendState1.srcColorBlendFactor = VkBlendFactor(HYD_BLEND_FACTOR_SRC_ALPHA);
        BlendState1.dstColorBlendFactor = VkBlendFactor(HYD_BLEND_FACTOR_ONE_MINUS_SRC_ALPHA);

        BlendState1.alphaBlendOp        = VkBlendOp(HYD_BLEND_OP_ADD);
        BlendState1.srcAlphaBlendFactor = VkBlendFactor(HYD_BLEND_FACTOR_ONE);
        BlendState1.dstAlphaBlendFactor = VkBlendFactor(HYD_BLEND_FACTOR_ZERO);


        PipelineConf.ColorBlending(
            {BlendState1}
        );


        Vec4<uint32> Viewport(
            0,
            0,
            Renderer::Self().GetWindow().GetWidth(),
            Renderer::Self().GetWindow().GetHeight()
        );

        PipelineConf.SetViewport(Viewport);

        m_Pipeline = Renderer::Self().CreatePipeline(PipelineConf);

        Log::SetInfo(Log::FmtStr("Alignment:%i\tSize:%i", alignof(GridUniformData), sizeof(GridUniformData)));
    }


    void Grid::Render() noexcept
    {

        m_UniData.View           = Renderer::Self().GetCurrentCamera()->GetView();
        m_UniData.Projection     = Renderer::Self().GetCurrentCamera()->GetProjection();
        m_UniData.CameraPos      = Renderer::Self().GetCurrentCamera()->GetCameraPos();
        m_UniData.FogCoefficient = VecF3(0.05f, 0.0005f, 1.0f);

        Renderer::Self().AccessUniformBuffer(m_Uniform).UploadData(
            &m_UniData,
            sizeof(GridUniformData)
        );


        Instruction instruction;
        instruction.Vertices    = m_VertexBuffer;
        instruction.Indices     = m_IndexBuffer;
        instruction.Pipeline    = m_Pipeline;
        instruction.Uniform     = m_Uniform;
        instruction.MaterialPtr = nullptr;

        
        Renderer::Self().PushInstruction(
            std::move(instruction)
        );
    }

    void Grid::DestroyGrid()  noexcept
    {
        m_VertexBuffer.Reset();
        m_IndexBuffer.Reset();
        m_Pipeline.Reset();
        m_Uniform.Reset();
    }


