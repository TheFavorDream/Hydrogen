    void Grid::GenerateGrid() noexcept
    {
        //Create a quad
        std::vector<VecF2> Positions = 
        {
            VecF2( -0.5, -0.5f),
            VecF2( -0.5f, 0.5f),
            VecF2(  0.5f, 0.5f),
            VecF2(  0.5f,-0.5f)
        };

        uint16 Indices[] = {
            0, 1, 2,
            1, 2, 3
        };

        m_VertexBuffer = Renderer::Self().InstanceVertexBuffer();
        m_VertexBuffer->CreateBuffer(sizeof(VecF2)*4);
        m_VertexBuffer->UploadData(Positions.data(), sizeof(VecF2)*4);

        m_IndexBuffer = Renderer::Self().InstanceIndexBuffer();
        m_IndexBuffer->CreateBuffer(sizeof(uint16)*6, 6, VK_INDEX_TYPE_UINT16);
        m_IndexBuffer->UploadData(Indices, sizeof(uint16)*6);



        //Pipeline Layout:
        PipelineLayoutConfiguration LayoutConf;
        HYD_ID_SPACE LayoutID = Renderer::Self().CreatePipelineLayout(LayoutConf);


        //Create Pipeline:

        Hydrogen::Internal::Vulkan::VertexAttribute Attribute;
        Attribute.m_BindingDescriptions.push_back(
            VkVertexInputBindingDescription{
                .binding   = 0,
                .stride    = 0,
                .inputRate = VK_VERTEX_INPUT_RATE_VERTEX
        });

        Attribute.m_AttributeDescriptions.push_back(
            VkVertexInputAttributeDescription{
                .location = 0, 
                .binding  = 0,
                .format   = VK_FORMAT_R32G32_SFLOAT,
                .offset   = 0
            }
        );


        GraphicsPipelineConfiguration PipelineConf;

        ShaderConfiguration VertexSh{
            .Type      = HYD_STAGE_VERTEX_SHADER,
            //.Binary    = Buffer(reinterpret_cast<uint8*>(GridVertexShaderSPV), sizeof(GridVertexShaderSPV)),
            .Path      = "/home/Volta/Desktop/Dev/Hydrogen/SandBox/Shaders/GridVertex.spv",
            .EntryName = "main",
        };
        ShaderConfiguration FragmentSh{
            .Type      = HYD_STAGE_FRAGMENT_SHADER,
            //.Binary    = Buffer(reinterpret_cast<uint8*>(GridFragmentShaderSPV), sizeof(GridFragmentShaderSPV)),
            .Path      = "/home/Volta/Desktop/Dev/Hydrogen/SandBox/Shaders/GridFragment.spv",
            .EntryName = "main",
        };

        PipelineConf.SetPipelineLayout(LayoutID);
        PipelineConf.AddVertexBufferLayout(Attribute);
        PipelineConf.AttachShader(VertexSh);
        PipelineConf.AttachShader(FragmentSh);
        PipelineConf.SetPrimitiveTogology();
        PipelineConf.SetRasterizer();
        PipelineConf.SetDepthStencil(false, false);
        PipelineConf.SetSubpass(0);
        
        m_Pipeline = Renderer::Self().CreatePipeline(PipelineConf);
    }

